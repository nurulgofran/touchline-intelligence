import { useEffect, useState } from "react";

import { formatMetricValue, type RecoveryFixture, type RecoveryFixtureState } from "../types";

/**
 * Recovery example — a recorded test run.
 *
 * This section of the trace panel replays a genuine run of the real
 * workflow in which a deliberately invalid claim was injected, vetoed
 * by the Grounding step with a reason, sent back to the Explainer along
 * the workflow's back edge, corrected, verified and produced as an
 * accepted overlay. It is purely presentational: the trace comes from a
 * versioned fixture file, so the replay changes neither the live match
 * nor the shared audience, and it makes no model calls.
 *
 * The real fixture is generated by
 * `fixtures/recovery/generate_recovery_fixture.py` and shipped at
 * `web/public/fixtures/recovery-example.v1.json`; until it exists the
 * section shows an honest "not yet generated" state and the exact
 * generation command, never a fabricated example. The schema's `label`
 * is surfaced verbatim, and the run is identified as a RECORDED TEST
 * RUN, never a live incident.
 */

const FIXTURE_URL = "/fixtures/recovery-example.v1.json";

/** The fields the section renders. Anything less is not a fixture. */
function isRecoveryFixture(value: unknown): value is RecoveryFixture {
  if (typeof value !== "object" || value === null) return false;
  const record = value as Record<string, unknown>;
  const recovery = record.recovery as Record<string, unknown> | null;
  if (typeof recovery !== "object" || recovery === null) return false;
  return (
    record.fixture_format === "touchline.recovery-example" &&
    record.kind === "recorded-test-run" &&
    typeof record.label === "string" &&
    typeof record.injected_fault === "object" &&
    record.injected_fault !== null &&
    typeof recovery.veto === "object" &&
    recovery.veto !== null &&
    typeof recovery.veto_trace_entry === "object" &&
    recovery.veto_trace_entry !== null &&
    typeof recovery.corrected_claim === "object" &&
    recovery.corrected_claim !== null &&
    typeof recovery.acceptance === "object" &&
    recovery.acceptance !== null &&
    typeof recovery.overlay === "object" &&
    recovery.overlay !== null &&
    typeof record.providers === "object" &&
    record.providers !== null
  );
}

function useRecoveryFixture(): RecoveryFixtureState {
  const [state, setState] = useState<RecoveryFixtureState>({ kind: "loading" });

  useEffect(() => {
    let cancelled = false;
    fetch(FIXTURE_URL)
      .then(async (response) => {
        if (!response.ok) throw new Error("missing");
        const contentType = response.headers.get("content-type") ?? "";
        // The dev server and the built app fall back to index.html for
        // unknown paths: a 200 that is not JSON means no fixture.
        if (!contentType.includes("json")) throw new Error("missing");
        const text = await response.text();
        let parsed: unknown;
        try {
          parsed = JSON.parse(text) as unknown;
        } catch {
          throw new Error("missing");
        }
        if (!isRecoveryFixture(parsed)) {
          throw new Error("invalid");
        }
        return parsed;
      })
      .then((fixture) => {
        if (!cancelled) setState({ kind: "ready", fixture });
      })
      .catch((error: unknown) => {
        if (cancelled) return;
        if (error instanceof Error && error.message === "invalid") {
          setState({
            kind: "invalid",
            reason:
              "the fixture file exists but is not a valid recovery fixture",
          });
        } else {
          setState({ kind: "not-generated" });
        }
      });
    return () => {
      cancelled = true;
    };
  }, []);

  return state;
}

function StepTitle({ children }: { children: string }) {
  return (
    <h4 className="mt-3 text-[10px] font-bold uppercase tracking-[0.12em] text-ink-400 first:mt-1">
      {children}
    </h4>
  );
}

function ReadyFixture({ fixture }: { fixture: RecoveryFixture }) {
  const fault = fixture.injected_fault;
  const vetoEntry = fixture.recovery.veto_trace_entry;
  const corrected = fixture.recovery.corrected_claim;
  const acceptedOverlay = fixture.recovery.overlay;
  const providers = fixture.providers;
  const correctedMetric = corrected.metrics.find((metric) => metric.name === fault.metric);

  return (
    <div className="text-[11px] leading-snug">
      {/* The schema's honesty label, verbatim. */}
      <p className="border-l-2 border-signal-amber/60 bg-signal-amber/[0.08] px-2.5 py-1.5 text-signal-amber">
        {fixture.label}
      </p>

      <div
        data-recovery-summary
        data-accepted={fixture.recovery.acceptance.accepted}
        className="mt-3 rounded-md border border-ink-700 bg-ink-850 p-3"
      >
        <div className="grid grid-cols-3 gap-2">
          <div>
            <p className="text-[10px] font-semibold uppercase text-signal-red">Rejected</p>
            <p className="mt-1 font-display text-xl font-semibold tabular-nums text-ink-50">{formatMetricValue(fault.claimed_value)}</p>
          </div>
          <div>
            <p className="text-[10px] font-semibold uppercase text-pitch-200">Corrected</p>
            <p className="mt-1 font-display text-xl font-semibold tabular-nums text-ink-50">{correctedMetric ? formatMetricValue(correctedMetric.value) : "See claim"}</p>
          </div>
          <div>
            <p className="text-[10px] font-semibold uppercase text-ink-300">Grounding</p>
            <p className="mt-1 font-display text-xl font-semibold text-pitch-200">{fixture.recovery.acceptance.accepted ? "Accepted" : "Refused"}</p>
          </div>
        </div>
        <p className="mt-2 border-t border-ink-700 pt-2 text-[10px] text-ink-300">Grounding → Explainer → corrected claim</p>
        <p className="mt-1 text-[10px] text-ink-400">{providers.correction_provider} · {providers.template_fallback_used ? "template fallback used" : "no template fallback"}</p>
      </div>

      <StepTitle>1 · The injected fault</StepTitle>
      <p className="text-ink-300">{fault.description}</p>
      <dl className="mt-1 grid grid-cols-2 gap-x-3 text-[11px]">
        <dt className="text-ink-500">metric</dt>
        <dd className="text-right font-mono text-ink-300">
          {fault.metric}
        </dd>
        <dt className="text-ink-500">claimed</dt>
        <dd className="text-right font-mono font-semibold tabular-nums text-signal-red">
          {formatMetricValue(fault.claimed_value)}
        </dd>
        <dt className="text-ink-500">log says</dt>
        <dd className="text-right font-mono font-semibold tabular-nums text-pitch-300">
          {formatMetricValue(fault.true_value)}
        </dd>
      </dl>

      <StepTitle>2 · The veto</StepTitle>
      <ul className="list-disc pl-4 text-signal-red/90">
        {fixture.recovery.veto.reasons.map((reason, index) => (
          <li key={index}>{reason}</li>
        ))}
      </ul>

      <StepTitle>3 · The back edge</StepTitle>
      <p className="text-ink-300">
        <span className="font-mono font-semibold text-ink-200">
          {vetoEntry.from_stage} → {vetoEntry.to_stage}
        </span>{" "}
        refused the claim ({vetoEntry.kind}) and the objection went back
        to the Explainer:
      </p>
      <p className="mt-0.5 border-l-2 border-ink-700 bg-ink-900/60 px-2.5 py-1 font-mono text-[10px] text-ink-400">
        {vetoEntry.summary}
      </p>

      <StepTitle>4 · The correction</StepTitle>
      <p className="text-ink-300">{corrected.reading}</p>
      {corrected.metrics.length > 0 && (
        <dl className="mt-1 grid grid-cols-2 gap-x-3 text-[11px]">
          {corrected.metrics.map((metric) => (
            <div
              key={metric.name}
              className="col-span-2 grid grid-cols-2 gap-x-3"
            >
              <dt className="text-ink-500">{metric.name}</dt>
              <dd className="text-right font-mono tabular-nums text-ink-300">
                {formatMetricValue(metric.value)} {metric.unit}
              </dd>
            </div>
          ))}
        </dl>
      )}
      <p className="mt-1 text-pitch-300">
        {fixture.recovery.acceptance.accepted
          ? "The Grounding step verified the corrected claim and accepted it."
          : "The Grounding step did not accept the corrected claim."}
      </p>

      <StepTitle>5 · The accepted overlay</StepTitle>
      <p className="font-display text-[14px] font-semibold leading-snug text-ink-50">
        {acceptedOverlay.title}
      </p>
      <p className="mt-0.5 text-ink-300">{acceptedOverlay.body}</p>

      <StepTitle>Who served the run</StepTitle>
      <dl className="grid grid-cols-2 gap-x-3 text-[11px]">
        <dt className="text-ink-500">explainer</dt>
        <dd className="text-right font-mono text-ink-300">
          {providers.explainer}
        </dd>
        <dt className="text-ink-500">narrator</dt>
        <dd className="text-right font-mono text-ink-300">
          {providers.narrator}
        </dd>
        <dt className="text-ink-500">personalizer</dt>
        <dd className="text-right font-mono text-ink-300">
          {providers.personalizer}
        </dd>
        <dt className="text-ink-500">the correction</dt>
        <dd className="text-right font-mono text-ink-300">
          {providers.correction_provider}
        </dd>
        <dt className="text-ink-500">template fallback</dt>
        <dd className="text-right font-mono text-ink-300">
          {providers.template_fallback_used ? "used" : "not used"}
        </dd>
      </dl>

      <StepTitle>Recorded where</StepTitle>
      <p className="font-mono text-[10px] leading-relaxed text-ink-600">
        {fixture.generator.name} {fixture.generator.version} ·{" "}
        {fixture.fixture_version} · {fixture.test_context.match_id} ·{" "}
        {fixture.test_context.audience}/{fixture.test_context.locale}
        <br />
        {fixture.test_context.isolation}
        <br />
        {fixture.generator.command}
      </p>
    </div>
  );
}

function NotGenerated() {
  return (
    <div className="text-[11px] leading-snug text-ink-400">
      <p>
        <span className="font-semibold uppercase tracking-[0.1em] text-signal-amber">
          Recorded test run
        </span>{" "}
        — no recorded recovery example has been generated yet. The trace
        above is the live match; nothing here is a fabricated example.
      </p>
      <p className="mt-1.5">Generate it on a machine with Foundry credentials:</p>
      <pre className="mt-1 overflow-x-auto rounded-sm border border-ink-800 bg-ink-950 p-2 font-mono text-[10px] leading-relaxed text-ink-300">
        {`python fixtures/recovery/generate_recovery_fixture.py \\
  --provider foundry \\
  --out web/public/fixtures/recovery-example.v1.json`}
      </pre>
      <p className="mt-1.5">
        The generator refuses to write the fixture unless the correction
        genuinely succeeds without template fallback. The frontend image
        must be rebuilt after the file is placed, and the section picks it
        up automatically.
      </p>
    </div>
  );
}

export interface RecoveryReplaySectionProps {
  /** Whether the replay is open. */
  open: boolean;
  /** Open or close the replay. */
  onToggle: () => void;
}

export default function RecoveryReplaySection({
  open,
  onToggle,
}: RecoveryReplaySectionProps) {
  const state = useRecoveryFixture();

  return (
    <div
      className={[
        "flex min-h-0 flex-col border-t border-ink-800",
        open ? "flex-1" : "shrink-0",
      ].join(" ")}
    >
      <div className="px-3.5 py-2.5">
        <button
          type="button"
          onClick={onToggle}
          className="flex w-full items-center justify-between gap-2 text-left focus-ring"
          aria-expanded={open}
        >
          <span className="flex flex-wrap items-center gap-2">
            <span className="panel-title !text-left">
              Recovery example
            </span>
            {/*
              The honesty label, in the same words the fixture uses. It
              is the thing that stops a reader mistaking a recorded test
              for a live incident, so it is not a whisper.
            */}
            <span className="text-[10px] font-bold uppercase tracking-[0.12em] text-signal-amber">
              recorded test run
            </span>
          </span>
          <span className="font-mono text-[11px] text-ink-500" aria-hidden="true">
            {open ? "−" : "+"}
          </span>
        </button>
        <p className="mt-1 text-[10px] leading-snug text-ink-600">
          Replaying this changes neither the live match nor the shared
          audience, and it makes no model calls.
        </p>
      </div>

      {open && (
        <div className="min-h-0 flex-1 overflow-y-auto px-3.5 pb-2.5">
          {state.kind === "loading" && (
            <p className="py-3 text-center text-[11px] text-ink-500">
              looking for the recorded run…
            </p>
          )}
          {state.kind === "not-generated" && <NotGenerated />}
          {state.kind === "invalid" && (
            <p className="border-l-2 border-signal-red/60 bg-signal-red/[0.07] px-2.5 py-1.5 text-[11px] text-signal-red">
              {state.reason}
            </p>
          )}
          {state.kind === "ready" && <ReadyFixture fixture={state.fixture} />}
        </div>
      )}
    </div>
  );
}
